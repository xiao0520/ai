/**
 * SSE 事件类型
 */
export type SseEventType = 'content' | 'reasoning' | 'citation' | 'citations' | 'done' | 'error' | 'message';

/**
 * SSE 事件数据
 */
export interface SseEventData {
  /**
   * 事件类型
   */
  event: SseEventType;
  /**
   * 消息内容
   */
  content?: string;
  /**
   * 推理内容（深度思考模式）
   */
  reasoningContent?: string;
  /**
   * 错误信息
   */
  error?: string;
  /**
   * 是否完成
   */
  done?: boolean;
}

/** 聊天模型选择模式；当前用户端只启用指定模型模式。 */
export type ChatModelSelectionMode = 'FIXED' | 'AUTO';

/** GENERAL 不检索知识库；KNOWLEDGE 必须携带用户明确选择的知识库。 */
export type ChatKnowledgeMode = 'GENERAL' | 'KNOWLEDGE';

export interface ChatKnowledgeOptionVO {
  id: number | string;
  name: string;
}

/**
 * ChatRequest，描述：对话请求对象
 */
export interface SendDTO {
  /**
   * 模型选择模式；当前固定传 FIXED。
   */
  modelMode: ChatModelSelectionMode;
  /**
   * FIXED 模式传入的已授权模型ID（必填）
   */
  modelId?: number;
  /**
   * 智能体ID（传入时后端按智能体配置解析模型/工具/技能/知识库/提示词/是否深度思考）
   */
  agentId?: number;
  /** 本轮知识来源模式。 */
  chatMode: ChatKnowledgeMode;
  /**
   * 对话消息（必填）
   */
  content: string;
  /**
   * 会话id
   */
  sessionId: string;
  /** 浏览器请求标识，用于后续服务端幂等控制。 */
  clientRequestId?: string;
  /**
   * 知识库id
   */
  knowledgeId?: string;
  /**
   * 应用ID
   */
  appId?: string;
  /**
   * 对话id(每个聊天窗口都不一样)
   */
  uuid?: number;
  /**
   * 是否启用深度思考
   */
  enableThinking?: boolean;
  /**
   * 是否支持联网
   */
  enableInternet?: boolean;
}

/**
 * Message，描述：
 */
export interface Message {
  content?: string;
  name?: string;
  reasoning_content?: string;
  /**
   * 目前支持四个中角色参考官网，进行情景输入：
   * https://platform.openai.com/docs/guides/chat/introduction
   */
  role?: 'system' | 'user' | 'assistant' | 'function' | 'tool';
  tool_call_id?: string;
  /**
   * The tool calls generated by the model, such as function calls.
   */
  tool_calls?: ToolCalls[];
}

/**
 * ToolCalls，The tool calls generated by the model, such as function calls.
 */
export interface ToolCalls {
  function?: ToolCallFunction;
  /**
   * The ID of the tool call.
   */
  id?: string;
  /**
   * The type of the tool. Currently, only function is supported.
   */
  type?: string;
}

/**
 * ToolCallFunction，ToolCall 的 Function参数
 * The function that the model called.
 */
export interface ToolCallFunction {
  /**
   * 方法参数
   */
  arguments?: string;
  /**
   * 方法名
   */
  name?: string;
}

export interface GetChatListParams {
  pageNum?: number;
  pageSize?: number;
  sessionId?: string;
}

/**
 * ChatMessageVo，聊天消息视图对象 chat_message
 */
export interface ChatCitationVo {
  messageId?: number;
  citationId: string;
  title: string;
  titlePath?: string[];
  locator?: Record<string, unknown>;
  excerpt: string;
}
export interface ChatMessageVo {
  id?: number;
  citations?: ChatCitationVo[];
  content?: string;
  callStatus?: string;
  errorCode?: string;
  errorMessage?: string;
  modelName?: string;
  modelSelectionMode?: ChatModelSelectionMode;
  modelRevision?: number;
  routeReasonCode?: string;
  routePolicyRevision?: number;
  candidateSnapshotHash?: string;
  role?: string;
  sessionId?: string;
  totalTokens?: number;
  messageSeq?: number;
  createTime?: Date;
}

/**
 * 分页响应通用结构（R<Page<T>>）。
 */
export interface PageResult<T> {
  total?: number;
  rows?: T[];
  [key: string]: any;
}
